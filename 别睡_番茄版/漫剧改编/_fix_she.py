n = 0
for key, pairs in fixes.items():
    segid, cutidx = key.split("#")
    cut = get(segid, int(cutidx))
    assert cut is not None, key
    for old, new in pairs:
        if old in cut["shot"]:
            cut["shot"] = cut["shot"].replace(old, new)
            n += 1
        else:
            print("MISS:", key, "|", old, "||", cut["shot"])

# global punctuation cleanup on all shots
for ep in sb["episodes"]:
    for seg in ep.get("segments", []):
        for c in seg.get("cuts", []):
            if "shot" not in c:
                continue
            s = c["shot"]
            s = re.sub(r"：；", "；", s)
            s = re.sub(r"：。", "。", s)
            s = re.sub(r"：\s*$", "", s)
            s = re.sub(r"\s+", " ", s)
            c["shot"] = s.strip()

